/* node scripts/env-to-config.js
   Reads .env (falls back to .env.example, and real environment variables win) and writes js/config.js for the page.
   Keys that look like secrets are refused, because everything in config.js is public. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const file = [path.join(root, '.env'), path.join(root, '.env.example')].find((f) => fs.existsSync(f));
const vars = {};
if (file) {
  fs.readFileSync(file, 'utf8').split(/\r?\n/).forEach((line) => {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) vars[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  });
}
const out = {};
for (const k of Object.keys(vars)) {
  if (/SECRET|TOKEN|PASSWORD|API_?KEY|SPOTIFY/i.test(k)) { console.warn(`skipped ${k}: looks like a secret, config.js is public`); continue; }
  out[k] = process.env[k] !== undefined ? process.env[k] : vars[k];
}
fs.writeFileSync(path.join(root, 'js', 'config.js'),
  '/* Generated by scripts/env-to-config.js from .env. Do not edit by hand: change .env and run the script again. */\n' +
  'window.LINKS = ' + JSON.stringify(out, null, 2) + ';\n');
console.log(`wrote js/config.js (${Object.keys(out).length} values from ${file ? path.basename(file) : 'nothing'})`);
